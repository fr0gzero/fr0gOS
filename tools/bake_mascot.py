#!/usr/bin/env python3
"""Bake the 17-frame goggle-frog mascot into the HDZero goggle font: each frame is a fixed 2x2 block of font
cells. Identical cells (the goggles repeat across frames) share a glyph, so it fits the frog slot pool easily.

Writes new BTFL_000.bmp (HD) + BTFL_FHD_000.bmp (FHD) and a firmware header mapping frame -> its 4 glyphs,
plus a reconstruction preview that composites the frames back out of the baked font (proves the round-trip).

usage: bake_mascot.py <frames_dir> <stock_hd.bmp> <stock_fhd.bmp> <out_dir> <mascot.h>
"""
import hashlib
import os
import sys
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import frog_glyphs  # noqa: E402

FRAMES_DIR, STOCK_HD, STOCK_FHD, OUT_DIR, HEADER = sys.argv[1:6]
TRANS = (127, 127, 127)
NAMES = ["idle", "glanceL", "glanceR", "blink", "grin", "exclgrin", "hurt", "ko", "breath",
         "blinkH", "glanceU", "glanceD", "whoa", "dizzy", "pumped", "stars", "upsidedown"]
SLOTS = frog_glyphs.SLOTS          # the font slots the frog may use (not text/colour/symbols)
os.makedirs(OUT_DIR, exist_ok=True)


def load_frames():
    out = []
    for i, n in enumerate(NAMES):
        p = os.path.join(FRAMES_DIR, f"frame_{i + 1:02d}_{n}.png")
        out.append(Image.open(p).convert("RGBA"))
    return out


def block(frame, cw, ch):
    """fit the frog into a 2x2 block (2*cw x 2*ch), width-filled, vertically centred, on transparent"""
    bw, bh = cw * 2, ch * 2
    s = min(bw / frame.width, bh / frame.height)
    r = frame.resize((max(1, round(frame.width * s)), max(1, round(frame.height * s))), Image.LANCZOS)
    canvas = Image.new("RGBA", (bw, bh), (0, 0, 0, 0))
    canvas.paste(r, ((bw - r.width) // 2, (bh - r.height) // 2), r)
    return canvas


def to_font(cell):
    """RGBA cell -> RGB with the font's transparency key"""
    out = Image.new("RGB", cell.size, TRANS)
    px, op = cell.load(), out.load()
    for y in range(cell.height):
        for x in range(cell.width):
            r, g, b, a = px[x, y]
            if a >= 128:
                op[x, y] = (r, g, b)
    return out


def bake():
    frames = load_frames()
    hd = Image.open(STOCK_HD).convert("RGB")
    fhd = Image.open(STOCK_FHD).convert("RGB")
    HCW, HCH = hd.width // 16, hd.height // 32
    FCW, FCH = fhd.width // 16, fhd.height // 32

    uniq = {}            # md5(fhd cell) -> slot
    paint = {}           # slot -> (hd_cell_rgb, fhd_cell_rgb)
    frame_glyphs = []    # [frame][4] glyph codes, order TL,TR,BL,BR
    nextslot = 0
    for f in frames:
        bh = block(f, HCW, HCH)
        bf = block(f, FCW, FCH)
        glyphs = []
        for (col, row) in ((0, 0), (1, 0), (0, 1), (1, 1)):
            cf = bf.crop((col * FCW, row * FCH, (col + 1) * FCW, (row + 1) * FCH))
            ch = bh.crop((col * HCW, row * HCH, (col + 1) * HCW, (row + 1) * HCH))
            if cf.getbbox() is None:                 # fully transparent cell -> space, nothing to draw
                glyphs.append(0x20)
                continue
            key = hashlib.md5(cf.tobytes()).hexdigest()
            if key not in uniq:
                if nextslot >= len(SLOTS):
                    raise SystemExit(f"out of frog slots ({len(SLOTS)})")
                uniq[key] = SLOTS[nextslot]; nextslot += 1
                paint[uniq[key]] = (to_font(ch), to_font(cf))
            glyphs.append(uniq[key])
        frame_glyphs.append(glyphs)

    for slot, (chd, cfhd) in paint.items():
        hd.paste(chd, ((slot % 16) * HCW, (slot // 16) * HCH))
        fhd.paste(cfhd, ((slot % 16) * FCW, (slot // 16) * FCH))
    hd.save(os.path.join(OUT_DIR, "BTFL_000.bmp"), format="BMP")
    fhd.save(os.path.join(OUT_DIR, "BTFL_FHD_000.bmp"), format="BMP")
    print(f"baked {len(frames)} frames using {len(paint)} unique glyphs (of {len(SLOTS)} slots)")

    # header
    rows = ",\n    ".join("{ 0x%02X, 0x%02X, 0x%02X, 0x%02X }" % tuple(g) for g in frame_glyphs)
    enum = "".join(f"    FROG_M_{n.upper()},\n" for n in NAMES)
    open(HEADER, "w").write(f"""// Generated by tools/bake_mascot.py - do not edit by hand.
// fr0gOS goggle-frog mascot: each frame is a 2x2 block of goggle-font glyphs (order: TL, TR, BL, BR).
// Must match BTFL_000.bmp / BTFL_FHD_000.bmp on the goggle SD card.
#pragma once
#include <stdint.h>

#define FROG_MASCOT_COLS 2
#define FROG_MASCOT_ROWS 2
#define FROG_MASCOT_FRAMES {len(frame_glyphs)}

typedef enum {{
{enum}    FROG_M_COUNT
}} frogMascotFrame_e;

// [frame][cell], cell order: 0=top-left 1=top-right 2=bottom-left 3=bottom-right; 0x20 = blank
static const uint8_t frogMascot[FROG_MASCOT_FRAMES][4] = {{
    {rows}
}};
""")
    print("header", HEADER)

    # reconstruction preview: composite each frame back from the baked FHD font
    cols = 6
    pad, gap = 16, 14
    bw, bh = FCW * 2, FCH * 2
    cw2 = bw + gap
    chh = bh + 26
    rws = (len(frames) + cols - 1) // cols
    pv = Image.new("RGB", (pad * 2 + cols * cw2 - gap, pad * 2 + 24 + rws * chh), (18, 20, 24))
    from PIL import ImageDraw, ImageFont
    d = ImageDraw.Draw(pv)
    try:
        font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", 20)
        sm = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 14)
    except Exception:
        font = sm = None
    d.text((pad, pad - 2), "mascot reconstructed from the BAKED FHD goggle font (72x108 blocks)", fill=(200, 230, 210), font=font)
    for i, g in enumerate(frame_glyphs):
        cx = pad + (i % cols) * cw2
        cy = pad + 24 + (i // cols) * chh
        for ci, (col, row) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
            s = g[ci]
            cellimg = fhd.crop(((s % 16) * FCW, (s // 16) * FCH, (s % 16 + 1) * FCW, (s // 16 + 1) * FCH))
            cellimg = Image.composite(cellimg, Image.new("RGB", cellimg.size, (18, 20, 24)),
                                      cellimg.point(lambda v: 0).convert("L"))  # placeholder, replaced below
            rgb = fhd.crop(((s % 16) * FCW, (s // 16) * FCH, (s % 16 + 1) * FCW, (s // 16 + 1) * FCH))
            mask = Image.new("L", rgb.size, 0)
            mp, rp = mask.load(), rgb.load()
            for yy in range(rgb.height):
                for xx in range(rgb.width):
                    if rp[xx, yy] != TRANS:
                        mp[xx, yy] = 255
            pv.paste(rgb, (cx + col * FCW, cy + row * FCH), mask)
        d.text((cx, cy + bh + 4), f"{i + 1} {NAMES[i]}", fill=(150, 200, 170), font=sm)
    pv.save(os.path.join(OUT_DIR, "mascot_reconstructed.png"))
    print("preview", os.path.join(OUT_DIR, "mascot_reconstructed.png"))


if __name__ == "__main__":
    bake()
