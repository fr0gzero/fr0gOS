#!/usr/bin/env python3
"""fr0gOS font v3: bake ONLY the trimmed idle mascot onto a base font, reserving the stick-DATA glyph slots
(free_slots()[:8]) so the bottom-bar stick encoding survives. No live stick overlay, no LCARS caps.

usage: bake_v3.py <base_hd.bmp> <base_fhd.bmp> <frames_dir> <out_dir>
"""
import hashlib, os, sys
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import frog_glyphs

BASE_HD, BASE_FHD, FRAMES, OUT = sys.argv[1:5]
TRANS = (127, 127, 127)
RESERVED = set(frog_glyphs.free_slots()[:8])            # stick-data glyphs - do not overwrite
SLOTS = [s for s in frog_glyphs.SLOTS if s not in RESERVED]
os.makedirs(OUT, exist_ok=True)

MASCOT = ["idle", "blink", "glanceL", "glanceR", "glanceU", "glanceD", "breath", "blinkH",
          "pumped", "grin", "ko", "upsidedown"]

hd = Image.open(BASE_HD).convert("RGB")
fhd = Image.open(BASE_FHD).convert("RGB")
HCW, HCH = hd.width // 16, hd.height // 32
FCW, FCH = fhd.width // 16, fhd.height // 32
paint = {}
nextslot = [0]
def claim():
    if nextslot[0] >= len(SLOTS):
        raise SystemExit("out of frog slots")
    s = SLOTS[nextslot[0]]; nextslot[0] += 1; return s
def to_font(cell):
    out = Image.new("RGB", cell.size, TRANS); px, op = cell.load(), out.load()
    for y in range(cell.height):
        for x in range(cell.width):
            r, g, b, a = px[x, y]
            if a >= 128: op[x, y] = (r, g, b)
    return out
def block(frame, cw, ch):
    bw, bh = cw * 2, ch * 2
    s = min(bw / frame.width, bh / frame.height)
    r = frame.resize((max(1, round(frame.width * s)), max(1, round(frame.height * s))), Image.LANCZOS)
    c = Image.new("RGBA", (bw, bh), (0, 0, 0, 0))
    c.paste(r, ((bw - r.width) // 2, (bh - r.height) // 2), r)
    return c

uniq = {}
frame_glyphs = []
for n in MASCOT:
    fn = next(x for x in os.listdir(FRAMES) if x.endswith(n + ".png"))
    f = Image.open(os.path.join(FRAMES, fn)).convert("RGBA")
    bh, bf = block(f, HCW, HCH), block(f, FCW, FCH)
    gl = []
    for (col, row) in ((0, 0), (1, 0), (0, 1), (1, 1)):
        cf = bf.crop((col * FCW, row * FCH, (col + 1) * FCW, (row + 1) * FCH))
        chd = bh.crop((col * HCW, row * HCH, (col + 1) * HCW, (row + 1) * HCH))
        if cf.getbbox() is None:
            gl.append(0x20); continue
        key = hashlib.md5(cf.tobytes()).hexdigest()
        if key not in uniq:
            s = claim(); uniq[key] = s; paint[s] = (to_font(chd), to_font(cf))
        gl.append(uniq[key])
    frame_glyphs.append(gl)
print("mascot:", len(MASCOT), "frames,", nextslot[0], "glyphs; reserved stick-data:", [hex(x) for x in sorted(RESERVED)])

for slot, (chd, cfhd) in paint.items():
    hd.paste(chd, ((slot % 16) * HCW, (slot // 16) * HCH))
    fhd.paste(cfhd, ((slot % 16) * FCW, (slot // 16) * FCH))
hd.save(os.path.join(OUT, "BTFL_000.bmp"), "BMP")
fhd.save(os.path.join(OUT, "BTFL_FHD_000.bmp"), "BMP")

rows = ",\n    ".join("{ 0x%02X, 0x%02X, 0x%02X, 0x%02X }" % tuple(g) for g in frame_glyphs)
enum = "".join("    FROG_M_%s,\n" % n.upper() for n in MASCOT)
open(os.path.join(OUT, "frog_mascot.h"), "w").write(f"""// Generated by bake_v3.py - trimmed mascot, stick-data glyphs reserved.
#pragma once
#include <stdint.h>
#define FROG_MASCOT_COLS 2
#define FROG_MASCOT_ROWS 2
#define FROG_MASCOT_FRAMES {len(frame_glyphs)}
typedef enum {{
{enum}    FROG_M_COUNT
}} frogMascotFrame_e;
static const uint8_t frogMascot[FROG_MASCOT_FRAMES][4] = {{
    {rows}
}};
""")
print("wrote", OUT)
