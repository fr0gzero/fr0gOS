#!/usr/bin/env python3
"""The frog set as the firmware plays it: every frame of every animation, de-duplicated into goggle-font
glyphs, assigned to font slots fr0gOS doesn't need, plus the C tables (frog_anim.h) the frog engine plays.

Imported by build_hacker_font.py (which paints the glyphs into both BMPs). Run on its own to write the
header and print the slot map:

usage: frog_glyphs.py <frog_anim.h>
"""
import hashlib
import os
import sys
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import frog_anim as A  # noqa: E402
import frog_events as E  # noqa: E402
import frog_hop as HP  # noqa: E402
from frog_dos import W, H  # noqa: E402
from frog_dos2 import rot  # noqa: E402

# ---- the animations, exactly as signed off in frog_final.py, split where the firmware needs to hold ----
SPIN_FR = [rot(A.IDLE, -a) for a in (22, 45, 67, 90, 112, 135, 157)]
FLIP = A.ANIMS["flip"][1]
SQUASH = A.ANIMS["squash"][1]
ANIMS = [
    ("CRT", [(f, max(60, ms // 2)) for f, ms in A.ANIMS["boot"][1][:8]]),      # boot: CRT line opens
    ("REST", A.ANIMS["rest"][1]),
    ("PEEK", A.ANIMS["peekaboo"][1]),
    ("FLIP_IN", FLIP[1:11]),                                                     # spins over, rocks on its back
    ("FLIP_HOLD", FLIP[11:]),                                                    # looks around, kicks (loops)
    ("FLIP_OUT", [(f, 60) for f in reversed(SPIN_FR)] + [(A.IDLE, 200)]),
    ("LOWBATT", A.ANIMS["low_battery"][1]),                                      # loops on the voltage ledge
    ("SQUASH_IN", SQUASH[1:3]),
    ("SQUASH_OUT", SQUASH[4:6]),
    ("ARMED", E.EVENTS["armed"][1]),
    ("MODE", E.EVENTS["mode"][1]),
    ("PUNCH", E.EVENTS["punch"][1]),
    ("TRICK", E.EVENTS["trick_flip_roll"][1]),
    ("SPIN", E.EVENTS["trick_spin"][1]),
    ("CRASH", E.EVENTS["crash"][1]),
    ("RECORD", E.EVENTS["record"][1]),
    ("SAFE", [(A.IDLE, 300), (A.BLINK, 150), (E.SLEEPY, 1800)]),
    ("CELEBRATE", E.EVENTS["trick_spin"][1][1:-1] + E.EVENTS["record"][1][1:-1] + [(A.SMILE, 900)]),
    ("FIL_BLINK", [(A.BLINK, 140), (A.IDLE, 300)]),
    ("FIL_LOOKL", [(A.LOOK_L, 500), (A.IDLE, 200)]),
    ("FIL_LOOKR", [(A.LOOK_R, 500), (A.IDLE, 200)]),
    ("FIL_LOOKUP", [(A.LOOK_UP, 500), (A.IDLE, 200)]),
    ("FIL_SMILE", [(A.SMILE, 600), (A.IDLE, 200)]),
    ("FIL_DANCE", E.EVENTS["mode"][1][1:]),
]
POSES = [("IDLE", A.IDLE), ("BLINK", A.BLINK), ("SMILE", A.SMILE), ("SLEEPY", E.SLEEPY), ("CROUCH", HP.CROUCH),
         ("LAND", HP.LAND), ("SQUASHED", SQUASH[3][0]), ("STAR", E.STAR_EYES)]
HOPS = [("R", HP.HOP_R), ("L", HP.HOP_L)]

# Font slots the frog may take. All are symbols a whoop without GPS, baro, mag, AH or stick overlay never
# draws (or the retired boot logo / old frog). 0x0A and 0x0D are skipped: newline bytes in a string are asking
# for trouble. Order = preference.
SLOTS = (list(range(0xA0, 0xD0)) + [0xF9, 0xFA, 0xFB] + list(range(0x18, 0x1D)) +
         [0x70, 0x71, 0x72, 0x73, 0x74, 0x78, 0x7A, 0x7C, 0x7D, 0x7E, 0x7F] + list(range(0x8A, 0x90)) +
         [0x97, 0x9A, 0x02, 0x03, 0x05, 0x08, 0x09, 0x0B, 0x0C, 0x0F, 0x16, 0x17])


def _norm(im):
    """RGBA 36x54 with hard alpha"""
    cell = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    cell.paste(im, (0, 0), im)
    px = cell.load()
    for y in range(H):
        for x in range(W):
            r, g, b, a = px[x, y]
            px[x, y] = (r, g, b, 255) if a >= 128 else (0, 0, 0, 0)
    return cell


_glyphs = {}      # md5 -> (slot, image)


def slot(im):
    cell = _norm(im)
    k = hashlib.md5(cell.tobytes()).hexdigest()
    if k not in _glyphs:
        if len(_glyphs) >= len(SLOTS):
            raise SystemExit(f"frog needs more than {len(SLOTS)} glyph slots")
        _glyphs[k] = (SLOTS[len(_glyphs)], cell)
    return _glyphs[k][0]


TABLES = [(name, [(slot(f), ms) for f, ms in fr]) for name, fr in ANIMS]
POSE_SLOTS = [(name, slot(im)) for name, im in POSES]
HOP_SLOTS = [(name, [(slot(a), slot(b)) for a, b in pairs]) for name, pairs in HOPS]
for _n, fr in TABLES:
    for _g, ms in fr:
        assert 10 <= ms <= 2550 and ms % 10 == 0, (_n, ms)


def cells():
    """[(slot, RGBA 36x54 FHD image)] for every frog glyph"""
    return sorted(_glyphs.values(), key=lambda v: v[0])


def header():
    out = ["// Generated by tools/frog_glyphs.py - do not edit by hand.",
           "// fr0gOS frog: glyph slots and animation tables (must match the goggle font).",
           "#pragma once", "", "#include <stdint.h>", "",
           f"#define FROG_GLYPH_COUNT {len(_glyphs)}"]
    out += [f"#define FROG_G_{n:<9} 0x{s:02X}" for n, s in POSE_SLOTS]
    out += ["", "typedef enum {"] + [f"    FROG_ANIM_{n}," for n, _ in TABLES] + ["    FROG_ANIM_COUNT", "} frogAnimId_e;", ""]
    out += ["typedef struct {", "    uint8_t g;      // glyph", "    uint8_t t10;    // duration, 10 ms units",
            "} frogFrame_t;", "", "typedef struct {", "    const frogFrame_t *f;", "    uint8_t n;", "} frogAnim_t;", "",
            "#ifdef FROG_ANIM_TABLES"]
    for name, fr in TABLES:
        body = ", ".join(f"{{0x{g:02X},{ms // 10}}}" for g, ms in fr)
        out.append(f"static const frogFrame_t frogAnim_{name}[] = {{ {body} }};")
    out.append("static const frogAnim_t frogAnims[FROG_ANIM_COUNT] = {")
    out += [f"    {{ frogAnim_{n}, {len(fr)} }}," for n, fr in TABLES]
    out.append("};")
    out.append("// hop between two cells: [step][0] = the cell it leaves, [step][1] = the cell it lands in")
    for name, pairs in HOP_SLOTS:
        body = ", ".join(f"{{0x{a:02X},0x{b:02X}}}" for a, b in pairs)
        out.append(f"static const uint8_t frogHop{name}[{len(pairs)}][2] = {{ {body} }};")
    out += ["#endif", ""]
    return "\n".join(out)


if __name__ == "__main__":
    open(sys.argv[1], "w").write(header())
    print(len(_glyphs), "glyphs in", len(SLOTS), "slots; last used 0x%02X" % cells()[-1][0] if _glyphs else "")
    print("slots:", " ".join("%02X" % s for s, _ in cells()))
